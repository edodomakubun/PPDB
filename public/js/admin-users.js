document.addEventListener('DOMContentLoaded', async () => {
    // Check Auth
    const { data: { session } } = await supabaseClient.auth.getSession();
    if (!session) {
        window.location.href = '../login.html';
        return;
    }

    document.getElementById('user-email').innerText = session.user.email;
    document.getElementById('btn-logout').addEventListener('click', async () => {
        await supabaseClient.auth.signOut();
        window.location.href = '../login.html';
    });

    loadUsers();
});

async function loadUsers() {
    const tbody = document.getElementById('user-table-body');
    tbody.innerHTML = '<tr><td colspan="4" class="px-6 py-8 text-center text-slate-500">Memuat data...</td></tr>';

    try {
        const { data, error } = await supabaseClient
            .from('admin_profiles')
            .select('*')
            .order('created_at', { ascending: false });

        if (error) throw error;

        renderTable(data);
    } catch (err) {
        console.error(err);
        tbody.innerHTML = '<tr><td colspan="4" class="px-6 py-8 text-center text-red-500">Gagal memuat daftar panitia.</td></tr>';
    }
}

function renderTable(data) {
    const tbody = document.getElementById('user-table-body');
    tbody.innerHTML = '';

    if (!data || data.length === 0) {
        tbody.innerHTML = '<tr><td colspan="4" class="px-6 py-8 text-center text-slate-500">Belum ada data panitia lain.</td></tr>';
        return;
    }

    data.forEach(user => {
        const date = new Date(user.created_at).toLocaleDateString('id-ID');
        const row = `
            <tr class="hover:bg-slate-50">
                <td class="px-6 py-4 whitespace-nowrap text-sm text-slate-900 font-medium">${user.email}</td>
                <td class="px-6 py-4 whitespace-nowrap text-sm text-slate-500">${user.nama || '-'}</td>
                <td class="px-6 py-4 whitespace-nowrap text-sm text-slate-500">${date}</td>
                <td class="px-6 py-4 whitespace-nowrap text-right text-sm font-medium">
                    <button onclick="deleteUser('${user.id}')" class="text-red-600 hover:text-red-900">Hapus</button>
                </td>
            </tr>
        `;
        tbody.insertAdjacentHTML('beforeend', row);
    });
}

// Modal Logic
function openAddModal() {
    document.getElementById('modal-add-user').classList.remove('hidden');
}

function closeAddModal() {
    document.getElementById('modal-add-user').classList.add('hidden');
    document.getElementById('form-add-user').reset();
}

async function submitAddUser() {
    const form = document.getElementById('form-add-user');
    const formData = new FormData(form);
    const email = formData.get('email');
    const password = formData.get('password');
    const nama = formData.get('nama');

    if (!email || !password || password.length < 6) {
        Swal.fire('Error', 'Email wajib diisi dan Password minimal 6 karakter.', 'error');
        return;
    }

    try {
        Swal.fire({ title: 'Memproses...', didOpen: () => Swal.showLoading() });

        // 1. Create User in Supabase Auth
        // Note: With client-side anon key, this usually logs the current user out if 'autoSignIn' is true (default).
        // We assume 'autoSignIn: false' option if available in signUp, but standard JS client logs in the new user immediately.
        // WORKAROUND: We use a trick or accept that the current admin will be logged out.
        // For a simple app, getting logged out is acceptable behavior -> "Login with new account to verify".
        // HOWEVER, to keep Admin logged in, usually need a Backend function.
        // Alternative: Use a second client instance? No, cookie conflict.

        // Let's warn the user: "Anda akan logout setelah membuat akun baru."

        const confirm = await Swal.fire({
            title: 'Konfirmasi',
            text: "Karena alasan keamanan sistem, setelah membuat akun baru Anda akan otomatis logout. Lanjutkan?",
            icon: 'warning',
            showCancelButton: true,
            confirmButtonText: 'Ya, Buat Akun'
        });

        if (!confirm.isConfirmed) return;

        // 2. Insert to admin_profiles FIRST (if RLS allows insert by authenticated users)
        // We need to do this carefully. If we create Auth User first, we are logged out/switched.
        // If we insert to DB first, we are still Admin.

        // Wait, Auth ID is generated by Supabase. We don't know it yet.
        // Actually, we can just insert the Profile *after* logging back in? No.

        // STRATEGY:
        // 1. Insert into 'admin_profiles' table with the email (using current Admin session).
        // 2. Call signUp. This creates the Auth User.
        // 3. User is logged out.

        const { error: dbError } = await supabaseClient
            .from('admin_profiles')
            .insert([{ email, nama }]);

        if (dbError) throw dbError;

        // 3. Sign Up
        const { data, error: authError } = await supabaseClient.auth.signUp({
            email,
            password
        });

        if (authError) throw authError;

        await Swal.fire('Berhasil', 'Akun panitia berhasil dibuat. Silakan login kembali.', 'success');
        window.location.href = '../login.html';

    } catch (err) {
        console.error(err);
        Swal.fire('Gagal', err.message, 'error');
    }
}

async function deleteUser(id) {
    // Note: Admin cannot delete Auth Users via Client API.
    // This function only deletes the Profile record.
    // The Auth User remains but won't show in list.

    const result = await Swal.fire({
        title: 'Hapus dari daftar?',
        text: "Ini hanya menghapus data dari daftar profil, bukan menghapus akun login (butuh akses database langsung).",
        icon: 'warning',
        showCancelButton: true,
        confirmButtonColor: '#d33',
        confirmButtonText: 'Ya, Hapus'
    });

    if (result.isConfirmed) {
        try {
            const { error } = await supabaseClient
                .from('admin_profiles')
                .delete()
                .eq('id', id);

            if (error) throw error;

            Swal.fire('Terhapus', 'Profil dihapus.', 'success');
            loadUsers();
        } catch (err) {
            Swal.fire('Error', err.message, 'error');
        }
    }
}
